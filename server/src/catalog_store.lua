local skynet = require("skynet")
local crypt = require("skynet.crypt")
local json = require("cjson")

skynet.start(function()
    skynet.dispatch("lua", function(_, _, action, record)
        assert(action == "load" or action == "get" or action == "save")
        local data = crypt.base64encode(json.encode(record or {}))
        local process = assert(io.popen("python3 deploy/catalog.py " .. action .. " '" .. data .. "'", "r"))
        local output = process:read("a")
        local ok = process:close()
        skynet.retpack(ok and json.decode(output))
    end)
end)
