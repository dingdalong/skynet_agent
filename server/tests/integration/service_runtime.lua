local skynet = require("skynet.manager")
local rpc = require("rpc")
local codes = require("enum.error_code")

skynet.start(function()
    local ok, err = xpcall(function()
        skynet.timeout(1500, function() os.exit(99) end)
        assert(table.concat(table.copy({ "preload", "ready" }), ":") == "preload:ready")
        assert(not pcall(skynet.newservice, "missing_runtime_worker"), "不存在的服务主体必须启动失败")
        local address = skynet.newservice("runtime_worker")
        assert(rpc.call(address, "version") == codes.invalid_command)
        assert(rpc.call(address, "init", {}) == codes.succ)
        local result = table.pack(rpc.call(address, "echo", nil, false, "tail", nil))
        assert(result.n == 6 and result[1] == codes.succ and result[2] == skynet.self())
        assert(result[3] == nil and result[4] == false and result[5] == "tail" and result[6] == nil)
        assert(rpc.call(address, "ctor") == codes.invalid_command)
        assert(rpc.call(address, "failure") == codes.call_fail)
        assert(rpc.call(address, "wait", 310) == codes.timeout)
        skynet.sleep(10)
        local wait_code, value = rpc.call_no_timeout(address, "wait", 310)
        assert(wait_code == codes.succ and value == 2)
        result = table.pack(rpc.call_no_timeout(address, "echo", nil, false, "tail", nil))
        assert(result.n == 6 and result[1] == codes.succ and result[2] == skynet.self())
        assert(result[3] == nil and result[4] == false and result[5] == "tail" and result[6] == nil)
        local code, version, value, class_identity, stable_class = rpc.call(address, "version")
        assert(code == codes.succ and version == "v1" and value == 2 and stable_class)
        local prepared
        code, prepared = rpc.call(address, "prepare_update")
        assert(code == codes.succ and prepared)
        local updated, update_error = skynet.call(address, "debug", "HOTFIX", "runtime_worker")
        assert(updated, update_error)
        local updated_identity
        code, version, value, updated_identity, stable_class = rpc.call(address, "version")
        assert(code == codes.succ and version == "v2" and value == 2 and stable_class)
        assert(class_identity == updated_identity)
        assert(rpc.call(address, "close") == codes.succ)
        assert(rpc.call(address, "close") == codes.succ)
        assert(rpc.send(address, "status") == codes.succ)
        skynet.kill(address)
        assert(rpc.call(address, "version") == codes.call_fail)
        assert(rpc.call_no_timeout(address, "version") == codes.call_fail)
        assert(rpc.send(address, "status") == codes.call_fail)
    end, debug.traceback)
    io.stderr:write(ok and "SERVICE_RUNTIME_OK\n" or "SERVICE_RUNTIME_FAILED: " .. tostring(err) .. "\n")
    io.stderr:flush()
    os.exit(ok and 0 or 1)
end)
