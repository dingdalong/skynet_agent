import CoreFoundation
import Foundation
import OSLog

/// Native ownership survives React trees and WebView leases. All mutable state
/// is confined to one serial queue; external effects return through that queue.
public final class HostCore {
    public typealias Reply = (Result<[String: Any], Error>) -> Void
    public typealias Observer = ([String: Any]) -> Void
    public let queue = DispatchQueue(label: "app.skynet.host", qos: .userInitiated)
    let catalog: AppCatalog
    private let store: DocumentStore
    private let documentURL: URL
    private let makeRuntime: (DispatchQueue, Int) throws -> BusinessRuntime
    private let agentServices: AgentServices
    private var suspended = false
    private var suspendedApps: [String] = []
    private var document: HostDocument
    private var revision = 0
    private var observers: [UUID: Observer] = [:]
    private var leases: [UUID: (String, Observer)] = [:]
    private var apps: [String: AppActor] = [:]
    private var generations: [String: Int] = [:]
    private var quarantined: [String: String] = [:]
    private let logger = Logger(subsystem: "app.skynet.agent", category: "HostCore")
    private var stopped = false
    private lazy var resources = ResourceBroker(queue: queue) { [weak self] appId, event in
        if appId == "agent", event["error"] != nil { self?.agentServices.close() }
        self?.enqueue(appId, type: "command", name: "$resource", payload: event) { _ in }
    }

    private final class AppActor {
        let entry: AppCatalog.Entry
        let generation: Int
        var runtime: BusinessRuntime?
        var state: Any = NSNull()
        var revision = 0
        var ready = false
        var busy = false
        var error: String?
        var tasks: [String: UUID] = [:]
        var interrupted: [String] = []
        var mailbox: [([String: Any], Reply)] = []
        init(entry: AppCatalog.Entry, generation: Int) {
            self.entry = entry
            self.generation = generation
        }
    }

    public init(dataRoot: URL, builtins: URL, launcher: URL? = nil, executable: URL? = nil) throws {
        try FileManager.default.createDirectory(at: dataRoot, withIntermediateDirectories: true)
        #if os(macOS)
            guard let launcher, let executable else {
                throw failure("runtime", "macOS runtime paths required")
            }
            self.agentServices = try AgentServices(root: dataRoot, launcher: launcher)
            let profile = dataRoot.appendingPathComponent("runtime.sb")
            self.makeRuntime = {
                try RuntimeProcess(
                    queue: $0, launcher: launcher, executable: executable, profile: profile, generation: $1)
            }
        #else
            self.agentServices = try AgentServices(root: dataRoot)
            self.makeRuntime = { EmbeddedRuntime(queue: $0, generation: $1) }
        #endif
        self.store = try DocumentStore(root: dataRoot.appendingPathComponent("state"))
        self.documentURL = dataRoot.appendingPathComponent("host.json")
        #if os(macOS)
            self.catalog = try AppCatalog(root: dataRoot.appendingPathComponent("apps"), builtins: builtins)
        #else
            self.catalog = try AppCatalog(
                root: dataRoot.appendingPathComponent("apps"), builtins: builtins, allowInstalled: false)
        #endif
        if FileManager.default.fileExists(atPath: documentURL.path) {
            document = try JSONDecoder().decode(HostDocument.self, from: Data(contentsOf: documentURL))
        } else {
            document = HostDocument()
        }
        document.workspace.recent.removeAll { catalog.entries[$0] == nil }
        document.workspace.panes = document.workspace.panes.map { id in
            id.flatMap { catalog.entries[$0] == nil ? nil : $0 }
        }
        #if os(macOS)
            // The profile is generated by the trusted host, never supplied by apps.
            func escaped(_ path: String) -> String {
                path.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
            }
            let sandbox = """
                (version 1)
                (deny default)
                (allow process-exec (literal "\(escaped(executable.path))"))
                (allow file-read-metadata)
                (allow file-read* (literal "/") (subpath "/System") (subpath "/usr/lib") (subpath "/private/var/db/dyld")
                    (literal "\(escaped(executable.path))") (literal "/dev/urandom") (literal "/dev/null"))
                (allow file-write* (literal "/dev/null"))
                (allow sysctl-read)
                (allow mach-lookup (global-name "com.apple.system.logger"))
                (allow signal (target self))
                """
            try Data(sandbox.utf8).write(to: profile, options: .atomic)
        #endif
        logger.info("HostCore initialized; apps=\(self.catalog.entries.count), runtime=JavaScriptCore")
    }

    private func persist(_ candidate: HostDocument) throws {
        try JSONEncoder().encode(candidate).write(to: documentURL, options: [.atomic])
        document = candidate
    }

    public func observe(_ observer: @escaping Observer) -> UUID {
        let id = UUID()
        queue.async {
            self.observers[id] = observer
            observer(self.snapshot())
        }
        return id
    }
    public func unobserve(_ id: UUID) { queue.async { self.observers[id] = nil } }

    public func attach(appId: String, observer: @escaping Observer) -> UUID {
        let lease = UUID()
        queue.async {
            self.leases[lease] = (appId, observer)
            do {
                _ = try self.ensureApp(appId)
                observer(self.appSnapshot(appId))
            } catch { observer(["error": String(describing: error)]) }
        }
        return lease
    }
    public func detach(_ lease: UUID) { queue.async { self.leases[lease] = nil } }

    public func package(appId: String, completion: @escaping (AppCatalog.Entry?) -> Void) {
        queue.async { completion(self.catalog.entries[appId]) }
    }

    public func mayManageApps(lease: UUID, completion: @escaping (Bool) -> Void) {
        queue.async {
            guard let (appId, _) = self.leases[lease] else {
                completion(false)
                return
            }
            do {
                try self.require(appId, "host.apps")
                completion(true)
            } catch { completion(false) }
        }
    }

    /// Identity comes from the native-created lease, not an appId in JSON.
    public func request(lease: UUID, kind: String, input: [String: Any], completion: @escaping Reply) {
        queue.async {
            guard let (appId, _) = self.leases[lease] else {
                completion(.failure(failure("lease", "View lease expired")))
                return
            }
            let reply: Reply = { result in
                guard self.leases[lease]?.0 == appId else { return }
                completion(result)
            }
            do {
                guard try jsonData(input).count <= 1_048_576 else {
                    throw failure("size", "Bridge input too large")
                }
                switch kind {
                case "snapshot": reply(.success(self.appSnapshot(appId)))
                case "agent.directory.choose", "agent.server.authorize", "agent.remote.set":
                    try self.requireBuiltinAgent(appId)
                    let completed: Reply = { result in
                        self.queue.async {
                            if case .success(let value) = result, value["cancelled"] as? Bool != true {
                                self.enqueue(
                                    appId, type: "command", name: "$agent.context",
                                    payload: value["context"] ?? value
                                ) { _ in }
                            }
                            reply(result)
                        }
                    }
                    if kind == "agent.directory.choose" {
                        self.agentServices.chooseDirectory(completion: completed)
                    } else if kind == "agent.server.authorize" {
                        guard let url = input["url"] as? String else { throw failure("network", "服务器地址必填") }
                        self.agentServices.authorize(url, completion: completed)
                    } else {
                        guard let value = input["enabled"] as? NSNumber,
                            CFGetTypeID(value) == CFBooleanGetTypeID()
                        else { throw failure("permission", "远程执行设置无效") }
                        self.agentServices.setRemote(value.boolValue, completion: completed)
                    }
                case "view.error":
                    let message = String((input["message"] as? String ?? "Unknown view failure").prefix(2048))
                    self.report(failure("view", message), appId: appId)
                    reply(.success([:]))
                case "command":
                    guard let name = input["name"] as? String, !name.hasPrefix("$") else {
                        throw failure("command", "Invalid app command")
                    }
                    self.enqueue(
                        appId, type: "command", name: name, payload: input["payload"] ?? NSNull(),
                        completion: reply)
                case "action":
                    guard let target = input["target"] as? String, let name = input["name"] as? String else {
                        throw failure("action", "Target and action required")
                    }
                    try self.call(
                        caller: appId, target: target, action: name, input: input["input"] ?? NSNull(),
                        completion: reply)
                case "task.cancel":
                    guard let id = input["taskId"] as? String, let actor = self.apps[appId],
                        actor.tasks[id] != nil
                    else { throw failure("task", "Unknown pending task") }
                    var tasks = actor.tasks
                    tasks[id] = nil
                    try self.commit(actor, state: actor.state, tasks: tasks)
                    self.enqueue(
                        appId, type: "command", name: "$effect",
                        payload: ["id": id, "error": "cancelled"], completion: { _ in })
                    reply(.success([:]))
                case "preferences.set":
                    try self.require(appId, "host.preferences")
                    try self.setPreferences(input)
                    reply(.success(self.preferences()))
                case "apps.list":
                    try self.require(appId, "host.apps")
                    reply(.success(["apps": self.catalog.entries.values.map { self.summary($0) }]))
                case "apps.remove":
                    try self.require(appId, "host.apps")
                    guard let target = input["appId"] as? String else { throw failure("app", "App required") }
                    try self.remove(target)
                    reply(.success([:]))
                case "apps.restart":
                    try self.require(appId, "host.apps")
                    guard let target = input["appId"] as? String else { throw failure("app", "App required") }
                    try self.restart(target)
                    reply(.success([:]))
                default: throw failure("bridge", "Unsupported bridge operation")
                }
            } catch {
                self.report(error, appId: appId)
                reply(.failure(error))
            }
        }
    }

    public func workspace(_ command: String, input: [String: Any] = [:], completion: Reply? = nil) {
        queue.async {
            do {
                if command == "restart" {
                    guard let id = input["appId"] as? String else { throw failure("app", "App required") }
                    try self.restart(id)
                    completion?(.success(self.snapshot()))
                    return
                }
                var candidate = self.document
                try candidate.workspace.apply(command, input, knownApps: Set(self.catalog.entries.keys))
                try self.persist(candidate)
                if let id = input["appId"] as? String,
                    ["open", "restore", "split"].contains(command)
                {
                    _ = try self.ensureApp(id)
                }
                if command == "close", let id = input["appId"] as? String { self.stopApp(id) }
                self.publish()
                completion?(.success(self.snapshot()))
            } catch {
                self.report(error)
                completion?(.failure(error))
            }
        }
    }

    private func ensureApp(_ id: String) throws -> AppActor {
        if let error = quarantined[id] { throw failure("runtime", error) }
        if let actor = apps[id] { return actor }
        guard apps.count < 16 else { throw failure("limit", "At most 16 apps may run at once") }
        guard !stopped, !suspended, let entry = catalog.entries[id] else {
            throw failure("app", "App unavailable or host suspended")
        }
        let generation = (generations[id] ?? 0) + 1
        generations[id] = generation
        let actor = AppActor(entry: entry, generation: generation)
        if let saved = try store.read(id) {
            actor.state = saved["state"] ?? NSNull()
            actor.revision = saved["revision"] as? Int ?? 0
            actor.interrupted = saved["pendingTasks"] as? [String] ?? []
            actor.tasks = Dictionary(uniqueKeysWithValues: actor.interrupted.map { ($0, UUID()) })
        }
        let code = try String(contentsOf: entry.root.appendingPathComponent("runtime.js"), encoding: .utf8)
        let runtime = try makeRuntime(queue, generation)
        actor.runtime = runtime
        apps[id] = actor
        runtime.onFailure = { [weak self, weak actor] error in
            guard let self, let actor, self.apps[id] === actor else { return }
            actor.error = String(describing: error)
            #if os(iOS)
                if (error as? HostError)?.code == "timeout" {
                    // iOS cannot force-stop a JSC thread. Refuse repeated VM creation
                    // after a timed-out built-in instead of accumulating stuck VMs.
                    self.quarantined[id] = String(describing: error)
                }
            #endif
            actor.ready = false
            actor.tasks.removeAll()
            self.resources.close(appId: id)
            if id == "agent" { self.agentServices.close() }
            let pending = actor.mailbox
            actor.mailbox.removeAll()
            for (_, reply) in pending { reply(.failure(error)) }
            self.report(error, appId: id)
            self.publish()
        }
        runtime.request(["type": "load", "code": code, "state": actor.state]) {
            [weak self, weak actor] result in
            guard let self, let actor, self.apps[id] === actor else { return }
            do {
                let value = try result.get()
                try self.commit(actor, state: value["state"] ?? NSNull())
                var startup: [([String: Any], Reply)] = []
                if !actor.interrupted.isEmpty {
                    startup.append(
                        (
                            [
                                "type": "command", "name": "$interrupted",
                                "payload": ["tasks": actor.interrupted],
                            ], { _ in }
                        ))
                }
                startup.append((["type": "start", "name": "$start", "payload": NSNull()], { _ in }))
                actor.mailbox.insert(contentsOf: startup, at: 0)
                actor.ready = true
                self.pump(actor)
            } catch {
                actor.error = String(describing: error)
                actor.runtime?.stop(error)
                self.report(error, appId: id)
            }
            self.publish()
        }
        return actor
    }

    private func enqueue(_ id: String, type: String, name: String, payload: Any, completion: @escaping Reply)
    {
        do {
            let actor = try ensureApp(id)
            guard actor.error == nil, actor.mailbox.count < 64 else {
                throw failure("unavailable", actor.error ?? "App mailbox full")
            }
            actor.mailbox.append((["type": type, "name": name, "payload": payload], completion))
            pump(actor)
        } catch { completion(.failure(error)) }
    }

    private func pump(_ actor: AppActor) {
        guard actor.ready, !actor.busy, !actor.mailbox.isEmpty, let runtime = actor.runtime else { return }
        let (message, reply) = actor.mailbox.removeFirst()
        let id = actor.entry.manifest.id
        actor.busy = true
        var frame = message
        frame["state"] = actor.state
        runtime.request(frame) { [weak self, weak actor] result in
            guard let self, let actor, self.apps[id] === actor else {
                reply(.failure(failure("generation", "App generation expired")))
                return
            }
            actor.busy = false
            do {
                let value = try result.get()
                let action =
                    message["type"] as? String == "action"
                    ? actor.entry.manifest.actions[message["name"] as? String ?? ""] : nil
                if let action {
                    try Schema.validate(value["result"] ?? NSNull(), against: action.output.value)
                }
                let effects = value["effects"] as? [[String: Any]] ?? []
                guard effects.count <= 16 else { throw failure("effects", "Too many effects") }
                var tasks = actor.tasks
                if message["name"] as? String == "$interrupted" {
                    for id in actor.interrupted { tasks[id] = nil }
                }
                for effect in effects {
                    guard let id = effect["id"] as? String, !id.isEmpty, id.count <= 128, tasks[id] == nil,
                        effect["kind"] is String
                    else { throw failure("effects", "Invalid or duplicate effect id") }
                    tasks[id] = UUID()
                }
                guard tasks.count <= 64 else { throw failure("effects", "Too many pending tasks") }
                try self.commit(actor, state: value["state"] ?? NSNull(), tasks: tasks)
                if message["name"] as? String == "$interrupted" { actor.interrupted.removeAll() }
                reply(.success(["result": value["result"] ?? NSNull(), "revision": actor.revision]))
                self.publish()
                // Effects start only after a durable commit; failures are events,
                // never automatic replay of an irreversible side effect.
                for effect in effects { self.perform(effect, actor: actor) }
            } catch {
                self.report(error, appId: id)
                reply(.failure(error))
            }
            self.pump(actor)
        }
    }

    private func commit(_ actor: AppActor, state: Any, tasks: [String: UUID]? = nil) throws {
        let next = actor.revision + 1
        let pending = tasks ?? actor.tasks
        try store.write(
            actor.entry.manifest.id, ["state": state, "revision": next, "pendingTasks": Array(pending.keys)])
        actor.state = state
        actor.revision = next
        actor.tasks = pending
    }

    private func perform(_ effect: [String: Any], actor: AppActor) {
        let appId = actor.entry.manifest.id
        guard let id = effect["id"] as? String, id.count <= 128,
            let kind = effect["kind"] as? String, let token = actor.tasks[id]
        else { return }
        let complete: Reply = { [weak self, weak actor] result in
            guard let self, let actor, self.apps[appId] === actor, actor.tasks[id] == token else { return }
            actor.tasks[id] = nil
            var event: [String: Any] = ["id": id]
            switch result {
            case .success(let value): event["value"] = value
            case .failure(let error):
                event["error"] = String(describing: error)
                self.report(error, appId: appId)
            }
            self.enqueue(appId, type: "command", name: "$effect", payload: event) { _ in }
        }
        do {
            let input = dictionary(effect["input"])
            switch kind {
            case "apps.call":
                guard let target = input["target"] as? String, let name = input["name"] as? String else {
                    throw failure("action", "Target/action missing")
                }
                try call(
                    caller: appId, target: target, action: name, input: input["input"] ?? NSNull(),
                    completion: complete)
            case "socket.open", "socket.send", "socket.close":
                try require(appId, "network")
                if appId == "agent", kind == "socket.close" { agentServices.close() }
                if appId == "agent", actor.entry.builtin, kind == "socket.open" {
                    agentServices.origins { origins in
                        self.queue.async {
                            guard self.apps[appId] === actor, actor.tasks[id] == token else { return }
                            do {
                                try self.resources.request(
                                    appId: appId, generation: actor.generation,
                                    kind: kind, input: input,
                                    origins: actor.entry.manifest.networkOrigins + origins,
                                    completion: complete)
                            } catch { complete(.failure(error)) }
                        }
                    }
                } else {
                    try resources.request(
                        appId: appId, generation: actor.generation, kind: kind, input: input,
                        origins: actor.entry.manifest.networkOrigins, completion: complete)
                }
            case "agent.context", "agent.execute":
                try requireBuiltinAgent(appId)
                let reply: Reply = { result in self.queue.async { complete(result) } }
                if kind == "agent.context" {
                    agentServices.context(reset: true, completion: reply)
                } else {
                    agentServices.execute(input, completion: reply)
                }
            case "timer.wait":
                try resources.request(
                    appId: appId, generation: actor.generation, kind: kind, input: input,
                    origins: [], completion: complete)
            default: throw failure("capability", "Unsupported effect")
            }
        } catch { complete(.failure(error)) }
    }

    private func call(caller: String, target: String, action: String, input: Any, completion: @escaping Reply)
        throws
    {
        try require(caller, "apps.call:\(target):\(action)")
        guard let schema = catalog.entries[target]?.manifest.actions[action] else {
            throw failure("action", "Unknown exported action")
        }
        try Schema.validate(input, against: schema.input.value)
        enqueue(target, type: "action", name: action, payload: input, completion: completion)
    }

    private func require(_ appId: String, _ permission: String) throws {
        guard let entry = catalog.entries[appId], entry.manifest.permissions.contains(permission),
            entry.builtin || (document.grants[appId] ?? []).contains(permission)
        else {
            throw failure("permission", "\(appId) lacks \(permission)")
        }
    }
    private func requireBuiltinAgent(_ appId: String) throws {
        guard appId == "agent", catalog.entries[appId]?.builtin == true else {
            throw failure("permission", "仅受信任的内置 Agent 可以使用本机开发与服务器授权")
        }
    }

    private func preferences() -> [String: Any] {
        [
            "appearance": document.appearance, "wallpaper": document.wallpaper,
            "reduceMotion": document.reduceMotion,
        ]
    }
    private func setPreferences(_ input: [String: Any]) throws {
        var candidate = document
        guard Set(input.keys).isSubset(of: ["appearance", "wallpaper", "reduceMotion"]) else {
            throw failure("preferences", "Unknown preference")
        }
        if let raw = input["appearance"] {
            guard let value = raw as? String else {
                throw failure("preferences", "Appearance must be a string")
            }
            guard ["system", "light", "dark"].contains(value) else {
                throw failure("preferences", "Invalid appearance")
            }
            candidate.appearance = value
        }
        if let raw = input["wallpaper"] {
            guard let value = raw as? String else {
                throw failure("preferences", "Wallpaper must be a string")
            }
            guard ["coast", "dusk", "forest"].contains(value) else {
                throw failure("preferences", "Invalid wallpaper")
            }
            candidate.wallpaper = value
        }
        if let raw = input["reduceMotion"] {
            guard let value = raw as? NSNumber, CFGetTypeID(value) == CFBooleanGetTypeID() else {
                throw failure("preferences", "Reduce motion must be a boolean")
            }
            candidate.reduceMotion = value.boolValue
        }
        try persist(candidate)
        publish()
    }

    private func summary(_ entry: AppCatalog.Entry) -> [String: Any] {
        var result = entry.manifest.summary
        let actor = apps[entry.manifest.id]
        result["builtin"] = entry.builtin
        result["status"] =
            actor?.error != nil || quarantined[entry.manifest.id] != nil
            ? "failed" : actor?.ready == true ? "running" : actor == nil ? "stopped" : "starting"
        result["error"] = actor?.error ?? quarantined[entry.manifest.id]
        result["pid"] = actor?.runtime?.pid ?? 0
        return result
    }
    private func appSnapshot(_ id: String) -> [String: Any] {
        [
            "appId": id, "generation": apps[id]?.generation ?? 0, "revision": apps[id]?.revision ?? 0,
            "state": apps[id]?.state ?? NSNull(), "preferences": preferences(),
            "apps": catalog.entries.values.sorted { $0.manifest.id < $1.manifest.id }.map(summary),
            "capabilities": capabilities,
            "error": apps[id]?.error as Any? ?? NSNull(),
        ]
    }
    private func snapshot() -> [String: Any] {
        [
            "revision": revision, "workspace": document.workspace.snapshot, "preferences": preferences(),
            "capabilities": capabilities,
            "apps": catalog.entries.values.sorted { $0.manifest.id < $1.manifest.id }.map(summary),
        ]
    }
    private func publish() {
        revision += 1
        let value = snapshot()
        for observer in Array(observers.values) { observer(value) }
        for (appId, observer) in Array(leases.values) { observer(appSnapshot(appId)) }
    }
    private func report(_ error: Error, appId: String = "host") {
        logger.error(
            "app=\(appId, privacy: .public) generation=\(self.apps[appId]?.generation ?? 0) revision=\(self.apps[appId]?.revision ?? 0) code=\((error as? HostError)?.code ?? "native", privacy: .public) error=\(String(describing: error), privacy: .public)"
        )
    }
    private func stopApp(_ id: String) {
        guard let actor = apps.removeValue(forKey: id) else { return }
        actor.runtime?.stop()
        resources.close(appId: id)
        if id == "agent" { agentServices.close() }
        for (_, reply) in actor.mailbox { reply(.failure(failure("stopped", "App closed"))) }
    }
    private func restart(_ id: String) throws {
        if let error = quarantined[id] { throw failure("runtime", error) }
        stopApp(id)
        _ = try ensureApp(id)
        publish()
    }
    private func remove(_ id: String) throws {
        var candidate = document
        candidate.grants[id] = nil
        candidate.workspace.recent.removeAll { $0 == id }
        candidate.workspace.panes = candidate.workspace.panes.map { $0 == id ? nil : $0 }
        try catalog.remove(id) { try persist(candidate) }
        stopApp(id)
        publish()
    }

    /// Called from the trusted native file picker after presenting the manifest
    /// permissions. Probe runs before touching the active app or its data.
    public func install(source: URL, approvedPermissions: [String], completion: @escaping Reply) {
        queue.async {
            guard self.capabilities["installApplications"] as? Bool == true else {
                completion(.failure(failure("capability", "此平台仅运行随安装包交付的内置应用")))
                return
            }
            var staged: URL?
            do {
                let (manifest, staging) = try self.catalog.stage(source)
                staged = staging
                guard Set(manifest.permissions) == Set(approvedPermissions) else {
                    try? FileManager.default.removeItem(at: staging)
                    throw failure("permission", "App permissions were not approved")
                }
                let generation = (self.generations[manifest.id] ?? 0) + 1
                let saved = try self.store.read(manifest.id)?["state"] ?? NSNull()
                let code = try String(
                    contentsOf: staging.appendingPathComponent("runtime.js"), encoding: .utf8)
                let probe = try self.makeRuntime(self.queue, generation)
                probe.request(["type": "load", "code": code, "state": saved]) { result in
                    defer {
                        probe.stop()
                        try? FileManager.default.removeItem(at: staging)
                    }
                    do {
                        _ = try result.get()
                        // Permissions are committed before activation. If moving
                        // the package fails, restore the exact previous grants.
                        let previous = self.document
                        var candidate = previous
                        candidate.grants[manifest.id] = approvedPermissions
                        try self.persist(candidate)
                        do { _ = try self.catalog.activate(manifest, staging: staging) } catch {
                            try self.persist(previous)
                            throw error
                        }
                        self.stopApp(manifest.id)
                        self.publish()
                        completion(.success(manifest.summary))
                    } catch {
                        self.report(error, appId: manifest.id)
                        completion(.failure(error))
                    }
                }
            } catch {
                if let staged { try? FileManager.default.removeItem(at: staged) }
                self.report(error)
                completion(.failure(error))
            }
        }
    }

    public func shutdown(completion: (() -> Void)? = nil) {
        queue.async {
            self.stopped = true
            for id in Array(self.apps.keys) { self.stopApp(id) }
            self.observers.removeAll()
            self.leases.removeAll()
            completion?()
        }
    }

    private var capabilities: [String: Any] {
        #if os(macOS)
            return [
                "platform": "macos", "splitView": true, "installApplications": true,
                "localDevelopment": true, "runtimeIsolation": "process",
            ]
        #else
            return [
                "platform": "ios", "splitView": true, "installApplications": false,
                "localDevelopment": false, "runtimeIsolation": "in-process",
            ]
        #endif
    }

    /// iOS background suspension is different from switching internal apps.
    /// Drop transport state; remote work continues on its actual execution owner.
    public func setBackgrounded(_ backgrounded: Bool, completion: (() -> Void)? = nil) {
        queue.async {
            guard !self.stopped, self.suspended != backgrounded else {
                completion?()
                return
            }
            self.suspended = backgrounded
            if backgrounded {
                self.suspendedApps = Array(self.apps.keys)
                // In-flight effects become interrupted, never replayed.
                for id in Array(self.apps.keys) { self.stopApp(id) }
            } else {
                let apps = self.suspendedApps
                self.suspendedApps = []
                for id in apps {
                    do { _ = try self.ensureApp(id) } catch { self.report(error, appId: id) }
                }
                self.publish()
            }
            completion?()
        }
    }

