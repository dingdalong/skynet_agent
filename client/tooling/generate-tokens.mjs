import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolveThemeTokens } from "@astryxdesign/core/theme";
import { neutralTheme } from "@astryxdesign/theme-neutral/built";

const root = fileURLToPath(new URL("../", import.meta.url));
const tokens = JSON.parse(
    await readFile(`${root}packages/tokens/tokens.json`, "utf8"),
);
const wallpapers = (mode) =>
    Object.entries(tokens.wallpapers)
        .map(
            ([name, colors]) =>
                `    --wallpaper-${name}: linear-gradient(145deg, ${colors[mode].join(", ")});`,
        )
        .join("\n");
const css = `/* Generated by tooling/generate-tokens.mjs. */\n:root {\n${wallpapers("light")}\n}\n:root[data-theme="dark"] {\n${wallpapers("dark")}\n}\n@media (prefers-color-scheme: dark) {\n    :root:not([data-theme]) {\n${wallpapers("dark").replaceAll("    --", "        --")}\n    }\n}\n`;
const light = resolveThemeTokens(neutralTheme, { mode: "light" });
const dark = resolveThemeTokens(neutralTheme, { mode: "dark" });
const hostTheme = {
    light: { background: light["--color-background-body"] },
    dark: { background: dark["--color-background-body"] },
};
const ts = `// Generated by tooling/generate-tokens.mjs.\nexport const tokens = ${JSON.stringify(tokens, null, 4)} as const;\n\nexport const hostTheme = ${JSON.stringify(hostTheme, null, 4)} as const;\n`;
const check = process.argv.includes("--check");
for (const [path, content] of [
    ["packages/tokens/theme.css", css],
    ["packages/tokens/theme.ts", ts],
]) {
    if (check) {
        if ((await readFile(`${root}${path}`, "utf8")) !== content)
            throw new Error(`Regenerate ${path}`);
    } else await writeFile(`${root}${path}`, content);
}
