import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolveThemeTokens } from "@astryxdesign/core/theme";
import { neutralTheme } from "@astryxdesign/theme-neutral/built";

const root = fileURLToPath(new URL("../", import.meta.url));
const tokens = JSON.parse(
    await readFile(`${root}packages/tokens/tokens.json`, "utf8"),
);
const wallpapers = (mode) =>
    Object.entries(tokens.wallpapers)
        .map(
            ([name, colors]) =>
                `    --wallpaper-${name}: linear-gradient(145deg, ${colors[mode].join(", ")});`,
        )
        .join("\n");
const css = `/* Generated by tooling/generate-tokens.mjs. */\n:root {\n${wallpapers("light")}\n}\n:root[data-theme="dark"] {\n${wallpapers("dark")}\n}\n@media (prefers-color-scheme: dark) {\n    :root:not([data-theme]) {\n${wallpapers("dark").replaceAll("    --", "        --")}\n    }\n}\n`;
const light = resolveThemeTokens(neutralTheme, { mode: "light" });
const dark = resolveThemeTokens(neutralTheme, { mode: "dark" });
function dimension(name, unit = "px") {
    const value = light[`--${name}`];
    const match = /^([\d.]+)(rem|px|ms)$/.exec(value);
    if (!match || (match[2] !== unit && !(unit === "px" && match[2] === "rem")))
        throw new Error(`Unsupported Astryx dimension ${name}: ${value}`);
    return Number(match[1]) * (match[2] === "rem" ? 16 : 1);
}
function palette(values, onWallpaper) {
    const roles = {
        background: "color-background-body",
        card: "color-background-surface",
        foreground: "color-text-primary",
        mutedForeground: "color-text-secondary",
        primary: "color-accent",
        primaryForeground: "color-on-accent",
        border: "color-border",
        divider: "color-border-emphasized",
        hover: "color-overlay-hover",
        pressed: "color-overlay-pressed",
        selected: "color-accent-muted",
        ring: "focus-outline-color",
        destructive: "color-text-error",
        shadow: "color-shadow",
        onWallpaper,
    };
    return Object.fromEntries(
        Object.entries(roles).map(([role, name]) => {
            const color = values[`--${name}`];
            if (!/^#(?:[\da-f]{6}|[\da-f]{8})$/i.test(color))
                throw new Error(`Unsupported Astryx color ${name}: ${color}`);
            return [role, color];
        }),
    );
}
const hostTheme = {
    light: palette(light, "color-on-light"),
    dark: palette(dark, "color-on-dark"),
    spacing: Object.fromEntries(
        [1, 2, 3, 4, 5, 6, 8, 12].map((step) => [
            step,
            dimension(`spacing-${step}`),
        ]),
    ),
    radius: {
        inner: dimension("radius-inner"),
        control: dimension("radius-element"),
        card: dimension("radius-container"),
        dock: dimension("radius-page"),
    },
    type: {
        label: dimension("text-label-size"),
        supporting: dimension("text-supporting-size"),
        heading: dimension("text-heading-3-size"),
    },
    button: dimension("size-element-lg"),
    compactButton: dimension("size-element-md"),
    focusWidth: dimension("focus-outline-width"),
    motion: {
        quick: dimension("duration-fast", "ms"),
        standard: dimension("duration-medium", "ms"),
    },
};
const ts = `// Generated by tooling/generate-tokens.mjs.\nexport const tokens = ${JSON.stringify(tokens, null, 4)} as const;\n\nexport const hostTheme = ${JSON.stringify(hostTheme, null, 4)} as const;\n`;
const check = process.argv.includes("--check");
for (const [path, content] of [
    ["packages/tokens/theme.css", css],
    ["packages/tokens/theme.ts", ts],
]) {
    if (check) {
        if ((await readFile(`${root}${path}`, "utf8")) !== content)
            throw new Error(`Regenerate ${path}`);
    } else await writeFile(`${root}${path}`, content);
}
