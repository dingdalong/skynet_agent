import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const tokens = JSON.parse(
    await readFile(`${root}packages/tokens/tokens.json`, "utf8"),
);
const kebab = (value) =>
    value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const theme = (values) => {
    const expanded = {
        ...values,
        cardForeground: values.foreground,
        popover: values.card,
        popoverForeground: values.foreground,
        secondary: values.muted,
        secondaryForeground: values.foreground,
        accent: values.muted,
        accentForeground: values.foreground,
        input: values.border,
    };
    return Object.entries(expanded)
        .map(([name, value]) => `    --${kebab(name)}: ${value};`)
        .join("\n");
};
const dimensions = [
    ...Object.entries(tokens.type).map(
        ([name, value]) => `    --type-${kebab(name)}: ${value}px;`,
    ),
    ...Object.entries(tokens.motion).map(
        ([name, value]) => `    --motion-${kebab(name)}: ${value}ms;`,
    ),
    ...Object.entries(tokens.touch).map(
        ([name, value]) => `    --touch-${kebab(name)}: ${value}px;`,
    ),
].join("\n");
const wallpapers = (mode) =>
    Object.entries(tokens.wallpapers)
        .map(
            ([name, colors]) =>
                `    --wallpaper-${name}: linear-gradient(145deg, ${colors[mode].join(", ")});`,
        )
        .join("\n");
const elevation = (mode) =>
    Object.entries(tokens.elevation[mode])
        .map(
            ([name, layers]) =>
                `    --shadow-${kebab(name)}: ${layers
                    .map(
                        ({ offsetX, offsetY, blurRadius, color }) =>
                            `${offsetX}px ${offsetY}px ${blurRadius}px ${color}`,
                    )
                    .join(", ")};`,
        )
        .join("\n");
const css = `/* Generated by tooling/generate-tokens.mjs. */\n:root {\n${theme(tokens.light)}\n${dimensions}\n${wallpapers("light")}\n${elevation("light")}\n    --radius: ${tokens.radius.control}px;\n}\n.dark {\n${theme(tokens.dark)}\n${wallpapers("dark")}\n${elevation("dark")}\n}\n`;
const ts = `// Generated by tooling/generate-tokens.mjs.\nexport const tokens = ${JSON.stringify(tokens, null, 4)} as const;\n`;
const check = process.argv.includes("--check");
for (const [path, content] of [
    ["packages/tokens/theme.css", css],
    ["packages/tokens/theme.ts", ts],
]) {
    if (check) {
        if ((await readFile(`${root}${path}`, "utf8")) !== content)
            throw new Error(`Regenerate ${path}`);
    } else await writeFile(`${root}${path}`, content);
}
